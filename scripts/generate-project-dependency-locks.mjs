import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { defaultProjectScaffoldFiles } from "../workers/main/src/project-scaffold.ts";

const root = resolve(import.meta.dirname, "..");
const warmupDir = join(root, "workers/main/project-build-sandbox-warmup");
const crudWarmupDir = join(warmupDir, "crud");
const outputPath = join(root, "workers/main/src/project-scaffold-lock.generated.ts");
const temp = mkdtempSync(join(tmpdir(), "camelai-scaffold-lock-"));

function generateLock(cwd) {
  const install = spawnSync(
    "bun",
    ["install", "--lockfile-only", "--ignore-scripts", "--no-progress"],
    { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
  if (install.status !== 0) {
    throw new Error(install.stderr || install.stdout || `bun install exited ${install.status}`);
  }
}

try {
  generateLock(warmupDir);

  const scaffold = defaultProjectScaffoldFiles("camelai-project", "crud", "camelai-project");
  const packageJson = scaffold.find((file) => file.path === "/package.json");
  if (!packageJson) throw new Error("CRUD scaffold did not produce package.json");
  writeFileSync(join(temp, "package.json"), packageJson.content);
  generateLock(temp);

  const lock = readFileSync(join(temp, "bun.lock"), "utf8");
  mkdirSync(crudWarmupDir, { recursive: true });
  writeFileSync(join(crudWarmupDir, "package.json"), packageJson.content);
  writeFileSync(join(crudWarmupDir, "bun.lock"), lock);
  writeFileSync(
    outputPath,
    `// Generated by scripts/generate-project-dependency-locks.mjs. Do not edit by hand.\n` +
      `export const DEFAULT_CRUD_BUN_LOCK = ${JSON.stringify(lock)};\n`,
  );
  console.log(`Wrote warmup locks and ${outputPath} (${Buffer.byteLength(lock)} scaffold lock bytes)`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
