#!/usr/bin/env node
// Regenerates the full Lucide icon-name list and SVG symbol sprite used by chat
// group avatars. Runtime application code imports the sprite as one asset and
// never loads lucide-react's dynamic registry. Run after upgrading lucide-react:
//   bun scripts/generate-lucide-icon-names.mjs
// Drift tests fail if either generated artifact diverges from the installed
// lucide-react version.
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
// Generation-only import: runtime src/ is forbidden from using this registry.
import {
  dynamicIconImports,
  iconNames,
} from "lucide-react/dynamic.mjs";

const names = [...iconNames].sort();
const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const namesTarget = join(
  repositoryRoot,
  "src",
  "lib",
  "lucide-icon-names.generated.ts",
);

const namesContents = `// AUTO-GENERATED by scripts/generate-lucide-icon-names.mjs — do not edit by hand.
// The full set of Lucide icon names (kebab-case) available to chat group avatars.
// Regenerate after upgrading lucide-react: bun scripts/generate-lucide-icon-names.mjs
// Drift tests enforce that this and the generated SVG sprite stay in sync.

export const LUCIDE_ICON_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)};
`;

function escapeXmlAttribute(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

const allowedTags = new Set([
  "circle",
  "ellipse",
  "line",
  "path",
  "polygon",
  "polyline",
  "rect",
]);

function serializeIconNode(name, iconNode) {
  if (!Array.isArray(iconNode)) {
    throw new Error(`Lucide icon ${name} does not export __iconNode`);
  }
  const nodes = iconNode.map(([tag, attributes]) => {
    if (!allowedTags.has(tag)) {
      throw new Error(`Lucide icon ${name} uses unsupported SVG tag ${tag}`);
    }
    const serializedAttributes = Object.entries(attributes)
      .filter(([attribute]) => attribute !== "key")
      .map(
        ([attribute, value]) =>
          `${attribute}="${escapeXmlAttribute(value)}"`,
      )
      .join(" ");
    return `<${tag}${serializedAttributes ? ` ${serializedAttributes}` : ""}/>`;
  });
  return `<symbol id="${escapeXmlAttribute(name)}" viewBox="0 0 24 24">${nodes.join("")}</symbol>`;
}

const symbols = [];
for (const name of names) {
  const loadIcon = dynamicIconImports[name];
  if (typeof loadIcon !== "function") {
    throw new Error(`Lucide dynamic registry has no loader for ${name}`);
  }
  const iconModule = await loadIcon();
  symbols.push(serializeIconNode(name, iconModule.__iconNode));
}

const spriteTarget = join(
  repositoryRoot,
  "src",
  "assets",
  "lucide-icon-sprite.generated.svg",
);
const spriteContents = `<!-- AUTO-GENERATED by scripts/generate-lucide-icon-names.mjs — do not edit. -->
<!-- Lucide ${names.length}-icon SVG symbol sprite; Lucide is licensed under ISC. -->
<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>
`;

writeFileSync(namesTarget, namesContents);
mkdirSync(dirname(spriteTarget), { recursive: true });
writeFileSync(spriteTarget, spriteContents);
console.log(`Wrote ${names.length} icon names to ${namesTarget}`);
console.log(`Wrote ${symbols.length} SVG symbols to ${spriteTarget}`);
