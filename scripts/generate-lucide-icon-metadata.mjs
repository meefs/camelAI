#!/usr/bin/env node
// Generates the compact, server-side Lucide metadata snapshot used for
// automatic chat-group icon selection. The source archive is downloaded only
// when this developer command runs; application builds never use the network.
//
// Run after upgrading lucide-react:
//   bun scripts/generate-lucide-icon-metadata.mjs
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { iconNames } from "lucide-react/dynamic.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = join(scriptDirectory, "..");
const packageJson = JSON.parse(
  readFileSync(
    join(repositoryRoot, "node_modules/lucide-react/package.json"),
    "utf8",
  ),
);
const version = packageJson.version;
if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(
    `Cannot determine installed lucide-react version: ${version}`,
  );
}

const archiveUrl = `https://github.com/lucide-icons/lucide/archive/refs/tags/${version}.tar.gz`;
const temporaryDirectory = mkdtempSync(
  join(tmpdir(), "camelai-lucide-metadata-"),
);
const archivePath = join(temporaryDirectory, "lucide.tar.gz");

try {
  const response = await fetch(archiveUrl, { redirect: "follow" });
  if (!response.ok) {
    throw new Error(
      `Failed to download Lucide ${version}: ${response.status} ${response.statusText}`,
    );
  }
  writeFileSync(archivePath, new Uint8Array(await response.arrayBuffer()));
  execFileSync("tar", ["-xzf", archivePath, "-C", temporaryDirectory], {
    stdio: "inherit",
  });

  const iconsDirectory = join(temporaryDirectory, `lucide-${version}`, "icons");
  const renderableNames = new Set(iconNames);
  const entries = readdirSync(iconsDirectory)
    .filter((fileName) => fileName.endsWith(".json"))
    .sort()
    .flatMap((fileName) => {
      const name = fileName.slice(0, -".json".length);
      const metadata = JSON.parse(
        readFileSync(join(iconsDirectory, fileName), "utf8"),
      );
      if (metadata.deprecated) return [];
      if (!renderableNames.has(name)) {
        throw new Error(
          `Lucide source icon ${name} is not renderable by lucide-react ${version}`,
        );
      }
      const aliases = [
        ...new Set((metadata.aliases ?? []).map((alias) => alias.name)),
      ].sort();
      return [
        {
          name,
          aliases,
          tags: [...metadata.tags].sort(),
          categories: [...metadata.categories].sort(),
        },
      ];
    });

  const duplicateNames = entries
    .map((entry) => entry.name)
    .filter((name, index, names) => names.indexOf(name) !== index);
  if (duplicateNames.length > 0) {
    throw new Error(
      `Duplicate Lucide metadata names: ${duplicateNames.join(", ")}`,
    );
  }

  const target = join(
    repositoryRoot,
    "src/lib/lucide-icon-metadata.generated.ts",
  );
  const lines = entries
    .map((entry) => `  ${JSON.stringify(entry)},`)
    .join("\n");
  const contents = `// AUTO-GENERATED by scripts/generate-lucide-icon-metadata.mjs — do not edit.
// Source: https://github.com/lucide-icons/lucide/tree/${version}/icons
// Regenerate after upgrading lucide-react.

export const LUCIDE_ICON_METADATA_VERSION = ${JSON.stringify(version)};

export interface LucideIconMetadataEntry {
  name: string;
  aliases: readonly string[];
  tags: readonly string[];
  categories: readonly string[];
}

export const LUCIDE_ICON_METADATA: readonly LucideIconMetadataEntry[] = [
${lines}
];
`;
  writeFileSync(target, contents);
  console.log(`Wrote ${entries.length} Lucide metadata entries to ${target}`);
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
